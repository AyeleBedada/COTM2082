let score = 0;
let answered = 0;
let correct = 0;

const quizContainer = document.getElementById('rmqQuestions');

function shuffleArray(arr){
  return arr.sort(()=>Math.random()-0.5);
}

rmqQuestions.forEach((question,index)=>{

  const card = document.createElement('div');
  card.className = 'rmq-card';

  const shuffled = question.options.map((opt,i)=>({
    text:opt,
    correct:i===question.answer
  }));

  shuffleArray(shuffled);

  card.innerHTML = `
    <div class="rmq-meta">
      <span>${question.difficulty}</span>
      <span>${question.subchapter}</span>
    </div>

    <h3>Q${index+1}. ${question.q}</h3>

    <p class="rmq-simple"><strong>Simple:</strong> ${question.simple}</p>

    <div class="rmq-options">
      ${shuffled.map((o,i)=>`
        <button class="rmq-option" data-correct="${o.correct}">
          ${String.fromCharCode(65+i)}. ${o.text}
        </button>
      `).join('')}
    </div>

    <div class="rmq-feedback"></div>
  `;

  const buttons = card.querySelectorAll('.rmq-option');
  const feedback = card.querySelector('.rmq-feedback');

  buttons.forEach(btn=>{
    btn.addEventListener('click',()=>{

      if(card.classList.contains('answered')) return;

      card.classList.add('answered');

      answered++;

      const isCorrect = btn.dataset.correct === 'true';

      buttons.forEach(b=>{
        b.disabled = true;
        if(b.dataset.correct === 'true'){
          b.classList.add('correct');
        }
      });

      if(isCorrect){
        btn.classList.add('correct');
        score += 2;
        correct++;

        feedback.innerHTML = `
          <div class="rmq-correct-box">
            ✔ Correct<br><br>
            ${question.explanation}
          </div>
        `;
      }else{
        btn.classList.add('wrong');

        feedback.innerHTML = `
          <div class="rmq-wrong-box">
            ✘ Incorrect<br><br>
            ${question.explanation}
          </div>
        `;
      }

      document.getElementById('rmqScore').textContent = score;
      document.getElementById('rmqAnswered').textContent = `${answered} / 50`;
      document.getElementById('rmqCorrect').textContent = correct;

    });
  });

  quizContainer.appendChild(card);

});

document.getElementById('rmqSubmitBtn').addEventListener('click',()=>{

  const percentage = ((correct / 50) * 100).toFixed(2);

  document.getElementById('rmqFinalResult').innerHTML = `
    <h2>Quiz Completed</h2>
    <p><strong>Final Score:</strong> ${score} / 100</p>
    <p><strong>Correct Answers:</strong> ${correct} / 50</p>
    <p><strong>Percentage:</strong> ${percentage}%</p>
    <p>Good work completing the coordination assessment.</p>
  `;

  window.scrollTo({ top:document.body.scrollHeight, behavior:'smooth' });

});